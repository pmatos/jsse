#!/usr/bin/env python3
"""Generate the tsc emit option matrix (issue #1245) from a compact spec.

    python3 scripts/gen-tsc-emit-cases.py [--check | --list]

Writes scripts/tsc-fixtures/cases-emit-{main,options,lang}.txt for scripts/run-tsc-projects-oracle.py. Every case
compiles files of the one project tree projects/emit. --check exits 1 when a generated file is stale; --list prints the case names.
"""

import os
import sys

FIX = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tsc-fixtures")

HEADER = "# generated by scripts/gen-tsc-emit-cases.py from a compact spec; edit the spec, not this file\n"
BASE = "--pretty false --lib es2020 --ignoreDeprecations 6.0"
MAIN = "src/main.ts"
GLOBALS = "globals.d.ts"
GROUP_NAMES = ["main", "options", "lang"]
GROUPS = {g: [] for g in GROUP_NAMES}


def case(group, name, args, files=MAIN, exit="0", out="--outDir out"):
    tail = " ".join(x for x in (BASE, out, args, files) if x)
    GROUPS[group].append(f"emit-{name} | emit | {exit} | {tail}")


def spec():
    targets = ["es5", "es2015", "es2017", "es2020", "es2022", "esnext"]
    mods = ["commonjs", "esnext", "amd", "umd", "system", "node16"]
    for t in targets:
        for m in mods:
            extra = " --downlevelIteration" if t == "es5" else ""
            case(
                "main",
                f"{t}-{m}",
                f"--target {t} --module {m}{extra} --declaration --sourceMap",
            )
    for m in ["es2020", "es2022", "nodenext", "node18", "node20", "preserve"]:
        case(
            "main",
            f"es2022-{m}",
            f"--target es2022 --module {m} --declaration --sourceMap",
        )
    case(
        "main",
        "es2022-es2015",
        "--target es2022 --module es2015 --declaration --sourceMap",
        "src/lib.ts",
    )
    pairs = [
        ("commonjs", "node10"),
        ("commonjs", "bundler"),
        ("esnext", "node10"),
        ("esnext", "bundler"),
        ("es2020", "bundler"),
        ("preserve", "bundler"),
        ("node16", "node16"),
        ("nodenext", "nodenext"),
        ("node20", "node16"),
    ]
    for m, r in pairs:
        case(
            "main",
            f"res-{m}-{r}",
            f"--target es2022 --module {m} --moduleResolution {r} --declaration",
        )
    for t in ["es2015", "es2020", "es2021", "es2022", "esnext"]:
        case(
            "main",
            f"priv-{t}",
            f"--target {t} --module commonjs --declaration",
            "src/priv.ts",
        )

    def opt(name, args="", target="es2020", **kw):
        module = "" if "--module" in args else " --module commonjs"
        case("options", name, f"--target {target}{module} {args}".rstrip(), **kw)

    opt("sourcemap", "--sourceMap")
    opt("inline-map", "--inlineSourceMap")
    opt("inline-map-sources", "--inlineSourceMap --inlineSources")
    opt("map-sources", "--sourceMap --inlineSources")
    opt("source-root", "--sourceMap --sourceRoot /srv/src")
    opt("map-root", "--sourceMap --mapRoot http://maps.example/m")
    opt("source-map-es5", "--sourceMap --downlevelIteration", target="es5")
    opt("decl", "--declaration")
    opt("decl-map", "--declaration --declarationMap")
    opt("decl-map-dir", "--declaration --declarationMap --declarationDir types")
    opt("decl-only", "--declaration --emitDeclarationOnly")
    opt(
        "decl-only-map",
        "--declaration --declarationMap --emitDeclarationOnly --sourceMap",
    )
    opt(
        "decl-esnext",
        "--declaration --declarationMap --module esnext --moduleResolution bundler",
    )
    opt("decl-strip-internal", "--declaration --stripInternal")
    opt("decl-remove-comments", "--declaration --removeComments")
    opt("remove-comments", "--removeComments")
    opt("remove-comments-map", "--removeComments --sourceMap --declaration")
    opt("newline-crlf", "--newLine crlf --sourceMap --declaration")
    opt("newline-lf", "--newLine lf")
    opt("emit-bom", "--emitBOM --declaration --sourceMap")
    opt("no-emit-helpers", "--noEmitHelpers --downlevelIteration", target="es5")
    opt("target-es5", "--downlevelIteration", target="es5")
    opt("target-es2015", target="es2015")
    opt("preserve-const-enums", "--preserveConstEnums --declaration")
    opt("isolated-modules", "--isolatedModules --module esnext")
    opt("isolated-modules-cjs", "--isolatedModules")
    opt(
        "verbatim-esnext",
        "--verbatimModuleSyntax --module esnext --moduleResolution bundler --declaration",
    )
    opt(
        "verbatim-nodenext",
        "--verbatimModuleSyntax --module nodenext",
        files="src/esm/pure.ts",
    )
    opt(
        "verbatim-nodenext-errors", "--verbatimModuleSyntax --module nodenext", exit="2"
    )
    opt("verbatim-cjs", "--verbatimModuleSyntax", exit="2")
    opt("es-module-interop", "--esModuleInterop")
    opt("es-module-interop-es5", "--esModuleInterop --downlevelIteration", target="es5")
    synth = "src/synth.ts src/cjsdep.d.ts"
    opt(
        "synthetic-default",
        "--allowSyntheticDefaultImports --module commonjs --moduleResolution node10",
        files=synth,
    )
    opt(
        "synthetic-default-off",
        "--allowSyntheticDefaultImports false --module commonjs --moduleResolution node10",
        files=synth,
        exit="2",
    )
    opt("synthetic-default-interop", "--esModuleInterop", files=synth)
    opt("define-fields-true", "--useDefineForClassFields true")
    opt("define-fields-false", "--useDefineForClassFields false", target="es2022")
    opt("no-check", "--noCheck --sourceMap")
    opt("erasable-syntax", "--erasableSyntaxOnly --noEmit", exit="2")
    opt("composite", "-p tsconfig.composite.json", files="")
    opt("incremental", "--incremental --tsBuildInfoFile out/info.tsbuildinfo")
    opt(
        "root-dir",
        "--module esnext --rootDir . --declaration --sourceMap",
        files="src/main.ts src/esm/entry.ts",
    )
    opt("list-emitted", "--listEmittedFiles --declaration --sourceMap")
    for m, r in [("esnext", "bundler"), ("commonjs", "node10"), ("amd", "node10")]:
        opt(
            f"rewrite-ext-{m}",
            f"--rewriteRelativeImportExtensions --module {m} --moduleResolution {r} --declaration",
            files="src/ext.ts",
        )
    opt(
        "rewrite-ext-nodenext",
        "--rewriteRelativeImportExtensions --module nodenext",
        files="src/ext.ts",
    )
    for m in ["amd", "system"]:
        for t in ["es5", "es2020"]:
            ds = " --downlevelIteration" if t == "es5" else ""
            case(
                "options",
                f"outfile-{m}-{t}",
                f"--module {m} --target {t}{ds}",
                out="--outFile out/bundle.js",
            )
    case(
        "options",
        "outfile-decl",
        "--module amd --target es2020 --declaration --declarationMap --sourceMap",
        out="--outFile out/bundle.js",
    )
    case(
        "options",
        "outfile-remove-comments",
        "--module system --target es2020 --removeComments --declaration",
        out="--outFile out/bundle.js",
    )
    case(
        "options",
        "outfile-inline-map",
        "--module amd --target es2020 --inlineSourceMap --inlineSources",
        out="--outFile out/bundle.js",
    )
    case(
        "options",
        "outfile-all",
        "--module amd --target es2020",
        files="src/main.ts src/priv.ts",
        out="--outFile out/all.js",
    )

    helpers = "-p tsconfig.helpers.json"
    for t, m in [
        ("es5", "commonjs"),
        ("es2015", "commonjs"),
        ("es2017", "esnext"),
        ("es2020", "commonjs"),
        ("es2022", "esnext"),
    ]:
        ds = " --downlevelIteration" if t == "es5" else ""
        case(
            "options",
            f"helpers-{t}-{m}",
            f"{helpers} --target {t} --module {m}{ds} --esModuleInterop --declaration",
            files="",
        )
    case(
        "options",
        "helpers-es5-map",
        f"{helpers} --target es5 --module amd --downlevelIteration --sourceMap",
        files="",
    )
    case(
        "options",
        "helpers-decorators-legacy-es5",
        "-p tsconfig.helpers-legacy.json --target es5 --module commonjs",
        files="",
    )
    case(
        "options",
        "helpers-decorators-legacy-es2022",
        "-p tsconfig.helpers-legacy.json --target es2022 --module esnext",
        files="",
    )
    for t in ["es2015", "es2022"]:
        case(
            "options",
            f"helpers-decorators-es-{t}",
            f"-p tsconfig.helpers-es.json --target {t} --module esnext",
            files="",
        )

    def jsx(name, args):
        case("lang", f"jsx-{name}", args, f"src/view.tsx {GLOBALS}")

    for mode in ["preserve", "react", "react-jsx", "react-jsxdev", "react-native"]:
        for m in ["commonjs", "esnext"]:
            jsx(f"{mode}-{m}", f"--target es2020 --module {m} --jsx {mode}")
    jsx("react-es5", "--target es5 --module commonjs --jsx react --downlevelIteration")
    jsx(
        "react-factory",
        "--target es2020 --module commonjs --jsx react --jsxFactory h --jsxFragmentFactory Frag",
    )
    jsx(
        "jsx-source",
        "--target es2020 --module commonjs --jsx react-jsx --jsxImportSource preact",
    )
    jsx(
        "dev-source",
        "--target es2020 --module esnext --jsx react-jsxdev --jsxImportSource preact",
    )
    jsx(
        "preserve-map",
        "--target esnext --module preserve --jsx preserve --sourceMap --declaration",
    )
    jsx(
        "react-map",
        "--target es2015 --module amd --jsx react --sourceMap --inlineSources",
    )
    jsx(
        "react-jsx-decl",
        "--target es2022 --module nodenext --jsx react-jsx --declaration --declarationMap",
    )
    jsx(
        "remove-comments",
        "--target es2020 --module commonjs --jsx react --removeComments",
    )

    def dec(name, args, files):
        case("lang", f"deco-{name}", args, files)

    for t in ["es5", "es2015", "es2022", "esnext"]:
        ds = " --downlevelIteration" if t == "es5" else ""
        dec(
            f"legacy-{t}",
            f"--target {t} --module commonjs --experimentalDecorators{ds}",
            "src/deco.ts",
        )
    for t in ["es2015", "es2022"]:
        dec(
            f"legacy-define-{t}",
            f"--target {t} --module commonjs --experimentalDecorators --useDefineForClassFields true",
            "src/deco.ts",
        )
    dec(
        "legacy-metadata-es2020",
        "--target es2020 --module commonjs --experimentalDecorators --emitDecoratorMetadata",
        "src/pdeco.ts",
    )
    dec(
        "legacy-metadata-esnext",
        "--target esnext --module esnext --experimentalDecorators --emitDecoratorMetadata --sourceMap",
        "src/pdeco.ts",
    )
    dec(
        "legacy-metadata-decl",
        "--target es2022 --module commonjs --experimentalDecorators --emitDecoratorMetadata --declaration",
        "src/pdeco.ts",
    )
    for t in ["es2015", "es2020", "es2022", "esnext"]:
        dec(f"es-{t}", f"--target {t} --module commonjs", "src/esdeco.ts")
    dec(
        "es-map",
        "--target es2020 --module esnext --sourceMap --declaration",
        "src/esdeco.ts",
    )
    dec(
        "es-deco-es5",
        "--target es5 --module commonjs --downlevelIteration",
        "src/deco.ts",
    )
    for t in ["es2015", "es2022", "esnext"]:
        dec(f"es-class-expr-{t}", f"--target {t} --module commonjs", "src/cexpr.ts")
    dec(
        "es-class-expr-decl",
        "--target es2022 --module esnext --declaration --sourceMap",
        "src/cexpr.ts",
    )

    for m in ["node16", "nodenext"]:
        case(
            "lang",
            f"mts-{m}",
            f"--target es2022 --module {m} --declaration --sourceMap",
            f"src/esm.mts {GLOBALS}",
        )
        case(
            "lang",
            f"cts-{m}",
            f"--target es2022 --module {m} --declaration --sourceMap",
            "src/cjs.cts",
        )
        case(
            "lang",
            f"mixed-{m}",
            f"--target es2022 --module {m} --declaration",
            f"src/main.ts src/esm.mts src/cjs.cts {GLOBALS}",
        )
        case(
            "lang",
            f"pkg-module-{m}",
            f"--target es2022 --module {m} --declaration --sourceMap",
            "src/esm/entry.ts",
        )
    case(
        "lang",
        "mts-preserve",
        "--target esnext --module preserve --moduleResolution bundler --declaration",
        f"src/esm.mts {GLOBALS}",
    )
    case(
        "lang",
        "mts-esnext",
        "--target esnext --module esnext --moduleResolution bundler",
        f"src/esm.mts {GLOBALS}",
    )
    case("lang", "cts-commonjs", "--target es2020 --module commonjs", "src/cjs.cts")
    case(
        "lang",
        "mts-decl-only",
        "--target es2022 --module nodenext --declaration --emitDeclarationOnly",
        f"src/esm.mts src/cjs.cts {GLOBALS}",
    )
    case(
        "lang",
        "mts-remove-comments",
        "--target es2022 --module nodenext --removeComments --declaration",
        f"src/esm.mts src/cjs.cts {GLOBALS}",
    )
    case(
        "lang",
        "mts-verbatim",
        "--target es2022 --module nodenext --verbatimModuleSyntax --declaration",
        f"src/pure.mts src/esm/pure.ts {GLOBALS}",
    )
    case(
        "lang",
        "mts-verbatim-cjs-errors",
        "--target es2022 --module nodenext --verbatimModuleSyntax",
        f"src/esm.mts src/esm/entry.ts {GLOBALS}",
        "2",
    )
    case(
        "lang",
        "mts-isolated",
        "--target es2022 --module nodenext --isolatedModules",
        f"src/esm.mts src/cjs.cts {GLOBALS}",
    )

    def js(name, args, files="js/plain.js js/esm.js", exit="0", out="--outDir out"):
        case("lang", f"js-{name}", args, files, exit, out)

    for t, m in [
        ("es5", "commonjs"),
        ("es2015", "commonjs"),
        ("es2020", "esnext"),
        ("es2022", "node16"),
        ("esnext", "preserve"),
    ]:
        js(f"{t}-{m}", f"--allowJs --target {t} --module {m}")
    js("decl", "--allowJs --declaration --target es2020 --module commonjs")
    js(
        "decl-map",
        "--allowJs --declaration --declarationMap --sourceMap --target es2020 --module esnext",
    )
    js(
        "decl-only",
        "--allowJs --declaration --emitDeclarationOnly --target es2022 --module nodenext",
    )
    js("check", "--allowJs --checkJs --target es2020 --module commonjs")
    js(
        "check-decl",
        "--allowJs --checkJs --declaration --target es2020 --module commonjs",
    )
    js(
        "check-errors",
        "--allowJs --checkJs --target es2020 --module esnext",
        "js/bad.js",
        "2",
    )
    js(
        "check-errors-no-emit",
        "--allowJs --checkJs --noEmitOnError --target es2020 --module esnext",
        "js/bad.js",
        "1",
    )
    js(
        "mixed",
        "--allowJs --target es2020 --module commonjs --declaration --sourceMap",
        "src/main.ts js/plain.js",
    )
    js(
        "mixed-es5",
        "--allowJs --target es5 --module amd --downlevelIteration --sourceMap",
        "src/main.ts js/plain.js",
    )
    js(
        "remove-comments",
        "--allowJs --removeComments --target es2020 --module commonjs",
        "js/plain.js js/esm.js",
    )
    js(
        "inline-map",
        "--allowJs --inlineSourceMap --target es2020 --module esnext",
        "js/esm.js",
    )
    js(
        "outfile",
        "--allowJs --module amd --target es2020 --declaration",
        out="--outFile out/bundle.js",
    )
    js(
        "outfile-mixed",
        "--allowJs --module system --target es2020 --declaration --sourceMap",
        "src/main.ts js/plain.js",
        out="--outFile out/bundle.js",
    )


def render():
    for rows in GROUPS.values():
        rows.clear()
    spec()
    return {
        f"cases-emit-{g}.txt": HEADER + "\n".join(GROUPS[g]) + "\n" for g in GROUP_NAMES
    }


def main():
    check = "--check" in sys.argv[1:]
    files = render()
    if "--list" in sys.argv[1:]:
        print(
            "\n".join(
                row.split(" | ")[0]
                for t in files.values()
                for row in t.splitlines()[1:]
            )
        )
        return 0
    stale = []
    for name, text in files.items():
        path = os.path.join(FIX, name)
        if check:
            try:
                with open(path, encoding="utf-8") as f:
                    if f.read() != text:
                        stale.append(name)
            except FileNotFoundError:
                stale.append(name)
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if stale:
        print("stale: " + ", ".join(stale) + " (run scripts/gen-tsc-emit-cases.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
